package data.remote.gemini

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Request body for Gemini's generateContent endpoint.
 *
 * The entire conversation history must be included
 * in contents for every request.
 */
@Serializable
data class GeminiGenerateContentRequest(
    @SerialName("system_instruction")
    val systemInstruction: GeminiContent,

    val contents: List<GeminiContent>
)

/**
 * Represents a message or system instruction.
 *
 * Gemini uses "user" and "model" as conversation roles.
 * The system instruction does not require a role.
 */
@Serializable
data class GeminiContent(
    val role: String? = null,
    val parts: List<GeminiPart>
)

/**
 * Represents a text part of a message.
 * This implementation supports text conversations.
 */
@Serializable
data class GeminiPart(
    val text: String
)

/**
 * Response body returned by Gemini's
 * generateContent endpoint.
 */
@Serializable
data class GeminiGenerateContentResponse(
    val candidates: List<GeminiCandidate> = emptyList()
)

/**
 * A possible response generated by Gemini.
 *
 * A candidate may not contain usable content,
 * for example when generation is blocked.
 */
@Serializable
data class GeminiCandidate(
    val content: GeminiContent? = null,

    @SerialName("finishReason")
    val finishReason: String? = null
)

/**
 * Standard error response returned by the Gemini API.
 *
 * Example:
 * {
 *   "error": {
 *     "code": 429,
 *     "message": "Resource exhausted",
 *     "status": "RESOURCE_EXHAUSTED"
 *   }
 * }
 */
@Serializable
data class GeminiErrorResponse(
    val error: GeminiApiError
)

/**
 * Error details returned by Gemini.
 */
@Serializable
data class GeminiApiError(
    val code: Int? = null,
    val message: String? = null,
    val status: String? = null
)
